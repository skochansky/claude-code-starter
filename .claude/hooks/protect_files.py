#!/usr/bin/env python3
"""PreToolUse(Edit|Write|MultiEdit): guard files Claude must never edit by hand.

- secrets (.env, keys, certificates)
- lock files and generated files (regenerate them with the tool instead)
- committed Django migrations (write a new migration instead)
- collected static files (run `collectstatic` instead)
- Claude Code's own settings and hooks (asks the user)
- CHANGELOG.md (generated by release tooling)
"""

import fnmatch
import re
import subprocess
from pathlib import Path

from _common import ask, deny, project_dir, read_event

SECRET_PATTERNS = [".env", ".env.*", "*.pem", "*.key", "*.p12", "id_rsa*", "secrets.*"]
SECRET_ALLOWLIST = [".env.example", ".env.sample", ".env.template"]
GENERATED = {
    "uv.lock": "Run `uv add` / `uv lock` instead of editing the lock file.",
    "poetry.lock": "Run `poetry add` / `poetry lock` instead of editing the lock file.",
    "CHANGELOG.md": "CHANGELOG.md is generated by release tooling.",
}
MIGRATION_DIRS = re.compile(r"(^|/)migrations/")
COLLECTED_DIRS = re.compile(r"^(staticfiles|media)/")
AUTOGEN_MARKERS = ("@generated", "auto-generated", "DO NOT EDIT")


def main() -> None:
    event = read_event()
    raw = event.get("tool_input", {}).get("file_path", "")
    if not raw:
        return
    path = Path(raw)
    name = path.name
    # Secrets are protected wherever they live, not only inside the project.
    if name not in SECRET_ALLOWLIST and any(fnmatch.fnmatch(name, p) for p in SECRET_PATTERNS):
        deny(f"{raw} may contain secrets. Ask the user to change it, or edit .env.example.")

    root = project_dir()
    try:
        rel = path.resolve().relative_to(root.resolve()).as_posix()
    except ValueError:
        return  # the remaining rules are about this project's files

    if name in GENERATED:
        deny(f"{rel} is generated. {GENERATED[name]}")

    if COLLECTED_DIRS.search(rel):
        deny(f"{rel} is collected/uploaded output. Edit the source file in the app instead.")

    # Claude must not quietly weaken its own guardrails.
    if rel == ".claude/settings.json" or rel.startswith(".claude/hooks/"):
        ask(f"{rel} controls Claude Code's own permissions/hooks. Confirm this change.")

    # Editing a migration that is already tracked by git rewrites history other
    # databases have applied. New (untracked) migration files are fine.
    if MIGRATION_DIRS.search(rel) and name != "__init__.py" and path.exists() and _is_tracked(rel):
        deny(
            f"{rel} is an existing migration. Never edit applied migrations; "
            "create a new one with `uv run python manage.py makemigrations`."
        )

    if path.is_file():
        head = "".join(path.read_text(encoding="utf-8", errors="ignore").splitlines(True)[:5])
        if any(marker in head for marker in AUTOGEN_MARKERS):
            deny(f"{rel} is marked as auto-generated. Change its source/generator instead.")


def _is_tracked(rel: str) -> bool:
    result = subprocess.run(
        ["git", "ls-files", "--error-unmatch", rel],
        cwd=project_dir(),
        capture_output=True,
        check=False,
    )
    return result.returncode == 0


if __name__ == "__main__":
    main()
